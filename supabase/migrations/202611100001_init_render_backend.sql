create extension if not exists pgcrypto;

create table if not exists public.tokens (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  token text not null,
  ws_url text,
  enabled boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.cron_tasks (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  cron_expr text not null,
  selected_tokens jsonb not null default '[]'::jsonb,
  selected_tasks jsonb not null default '[]'::jsonb,
  source_config jsonb,
  enabled boolean not null default true,
  last_run_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.cron_tasks
  add column if not exists source_config jsonb;

create table if not exists public.task_logs (
  id bigint generated by default as identity primary key,
  task_id uuid references public.cron_tasks(id) on delete cascade,
  token_name text,
  task_type text,
  status text,
  message text,
  created_at timestamptz not null default now()
);

create index if not exists task_logs_task_id_idx
  on public.task_logs(task_id);

create index if not exists task_logs_created_at_idx
  on public.task_logs(created_at);

alter table public.tokens enable row level security;
alter table public.cron_tasks enable row level security;
alter table public.task_logs enable row level security;

grant usage on schema public to service_role;
grant select, insert, update, delete
  on public.tokens, public.cron_tasks, public.task_logs
  to service_role;
grant usage, select
  on all sequences in schema public
  to service_role;
